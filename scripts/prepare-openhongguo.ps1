param([switch]$Android)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$work = Join-Path $root '.dart_tool'
$source = Join-Path $work 'openhongguo-src'
$stamp = Join-Path $source '.hongputao-kernel'
$revision = '113f076383f5f1b6cb14943806625b53bff2ec1f'
$patches = @(
  (Join-Path $PSScriptRoot 'patches/openhongguo-pr16.patch'),
  (Join-Path $PSScriptRoot 'patches/openhongguo-pr19-flutter.patch')
)
$expected = "$revision $((($patches | Get-FileHash).Hash) -join ' ')"
New-Item -ItemType Directory -Path $work -Force | Out-Null
if (!(Test-Path -LiteralPath $stamp) -or (Get-Content -LiteralPath $stamp -Raw).Trim() -ne $expected) {
  if (Test-Path -LiteralPath $source) {
    $resolved = (Resolve-Path -LiteralPath $source).Path
    if ($resolved -ne (Join-Path (Resolve-Path -LiteralPath $work).Path 'openhongguo-src')) {
      throw 'Generated SDK directory is outside its expected path'
    }
    Remove-Item -LiteralPath $resolved -Recurse -Force
  }
  $archive = Join-Path $work 'openhongguo-pinned.tar.gz'
  gh auth status -h github.com 2>&1 | Where-Object { $_ -notmatch '(?i)token' }
  if ($LASTEXITCODE -ne 0) { throw 'GitHub authentication is required to prepare the pinned SDK' }
  gh api "repos/J3n5en/openhongguo/tarball/$revision" > $archive
  if ($LASTEXITCODE -ne 0) { throw 'Pinned SDK source download failed' }
  $entries = tar -tzf $archive
  if ($LASTEXITCODE -ne 0 -or ($entries | Where-Object { $_ -match '(^/|^[A-Za-z]:|(?:^|/)\.\.(?:/|$))' })) {
    throw 'Unexpected SDK archive layout'
  }
  New-Item -ItemType Directory -Path $source | Out-Null
  tar -xzf $archive -C $source --strip-components 1
  if ($LASTEXITCODE -ne 0) { throw 'SDK source unpack failed' }
  Push-Location -LiteralPath $source
  try {
    git init -q
    if ($LASTEXITCODE -ne 0) { throw 'Could not initialize SDK build directory' }
    foreach ($patch in $patches) {
      git apply --check $patch
      if ($LASTEXITCODE -ne 0) { throw "SDK patch no longer applies: $patch" }
      git apply $patch
      if ($LASTEXITCODE -ne 0) { throw "Could not apply SDK patch: $patch" }
    }
  } finally { Pop-Location }
  Set-Content -LiteralPath $stamp -Value $expected
}

if (!$Android) { return }

$plugin = Join-Path $source 'bindings/flutter'
$androidPlugin = Join-Path $plugin 'android'
$coreJar = Join-Path $androidPlugin 'libs/core.jar'
$coreLib = Join-Path $androidPlugin 'src/main/jniLibs/arm64-v8a/libgojni.so'
if (!(Test-Path -LiteralPath $coreJar) -or !(Test-Path -LiteralPath $coreLib)) {
  $tools = Join-Path $work 'openhongguo-tools'
  New-Item -ItemType Directory -Path $tools -Force | Out-Null
  $env:GOBIN = $tools
  $env:GOTOOLCHAIN = 'go1.26.0'
  $env:PATH = $tools + [IO.Path]::PathSeparator + $env:PATH
  $gomobile = 'v0.0.0-20261011034528-197770444867'
  go install "golang.org/x/mobile/cmd/gomobile@$gomobile" "golang.org/x/mobile/cmd/gobind@$gomobile"
  if ($LASTEXITCODE -ne 0) { throw 'gomobile installation failed' }
  $aar = Join-Path $work 'openhongguo-core.aar'
  Push-Location -LiteralPath (Join-Path $source 'bindings/mobile/core')
  try {
    gomobile bind -target android/arm64 -androidapi 24 -javapkg dev.openhongguo -trimpath '-ldflags=-s -w' -o $aar .
    if ($LASTEXITCODE -ne 0) { throw 'OpenHongguo Android core build failed' }
  } finally { Pop-Location }
  $zip = [IO.Compression.ZipFile]::OpenRead($aar)
  try {
    foreach ($pair in @(@('classes.jar',$coreJar), @('jni/arm64-v8a/libgojni.so',$coreLib))) {
      $entry = $zip.GetEntry($pair[0])
      if (!$entry) { throw "SDK archive lacks $($pair[0])" }
      New-Item -ItemType Directory -Path (Split-Path $pair[1]) -Force | Out-Null
      [IO.Compression.ZipFileExtensions]::ExtractToFile($entry,$pair[1],$true)
    }
  } finally { $zip.Dispose() }
}
$override = Join-Path $root 'pubspec_overrides.yaml'
$marker = '# Generated by scripts/prepare-openhongguo.ps1'
$originalOverrides = [regex]::Match((Get-Content -LiteralPath (Join-Path $root 'pubspec.yaml') -Raw),
    '(?m)^dependency_overrides:[ \t]*\r?\n((?:[ \t]+[^\r\n]*\r?\n?)*)').Groups[1].Value
$contents = "$marker`ndependency_overrides:`n$originalOverrides  openhongguo:`n    path: .dart_tool/openhongguo-src/bindings/flutter"
if ((Test-Path -LiteralPath $override) -and !(Get-Content -LiteralPath $override -Raw).StartsWith($marker)) {
  throw 'Existing pubspec_overrides.yaml belongs to the developer; refusing to replace it'
}
Set-Content -LiteralPath $override -Value $contents -Encoding utf8
